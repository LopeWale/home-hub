/* MMM-GuestNet
 *
 * A small Raspberry Pi style network icon for the top bar: Wi-Fi bars, a
 * cable icon when wired, a cross when the internet is unreachable.
 * Tapping it opens a popup with the guest Wi-Fi QR code; guests scan it and
 * close the popup (or it closes itself after closeAfterMs).
 *
 * Sends GN_INIT / GN_GUEST_REQUEST to its node_helper.
 * Receives GN_STATUS {kind, signal, online} and GN_GUEST {ssid, password, svg} | {error}.
 */
Module.register("MMM-GuestNet", {
	defaults: {
		ssid: "", // empty: GUEST_WIFI_SSID from config.env
		password: "", // empty: GUEST_WIFI_PASSWORD from config.env
		security: "WPA", // WPA (also WPA2/WPA3), WEP or nopass
		hidden: false,
		showPassword: true,
		title: "Guest Wi-Fi",
		updateInterval: 30000,
		closeAfterMs: 2 * 60 * 1000
	},

	getStyles () {
		return ["MMM-GuestNet.css"];
	},

	start () {
		this.netStatus = null;
		this.guest = null;
		this.sendSocketNotification("GN_INIT", {
			ssid: this.config.ssid,
			password: this.config.password,
			security: this.config.security,
			hidden: this.config.hidden,
			updateInterval: this.config.updateInterval
		});
		document.addEventListener("keydown", (ev) => {
			if (ev.key === "Escape") this.closePopup();
		});
	},

	getDom () {
		if (!this.button) {
			this.button = document.createElement("button");
			this.button.type = "button";
			this.button.className = "gn-icon";
			this.button.addEventListener("click", (ev) => {
				ev.stopPropagation();
				this.openPopup();
			});
		}
		this.renderIcon();
		return this.button;
	},

	/* 24x24 icons drawn in the current text color. */
	iconSvg () {
		const s = this.netStatus;
		const cross = s && !s.online ? "<path class=\"gn-cross\" d=\"M15.5 15.5l6 6m0-6l-6 6\"/>" : "";
		if (s && s.kind === "ethernet") {
			return "<svg viewBox=\"0 0 24 24\" aria-hidden=\"true\"><path d=\"M8 20V5M8 5L4.5 8.5M8 5l3.5 3.5M16 4v15m0 0l-3.5-3.5M16 19l3.5-3.5\"/>" + cross + "</svg>";
		}
		const level = !s || s.kind !== "wifi" ? 0 : s.signal === null ? 3 : s.signal >= 67 ? 3 : s.signal >= 34 ? 2 : 1;
		const arc = (n, d) => "<path class=\"" + (level >= n ? "gn-on" : "gn-off") + "\" d=\"" + d + "\"/>";
		return "<svg viewBox=\"0 0 24 24\" aria-hidden=\"true\">" +
			arc(3, "M2.5 9.2a13.5 13.5 0 0 1 19 0") +
			arc(2, "M5.8 12.6a8.8 8.8 0 0 1 12.4 0") +
			arc(1, "M9.1 16a4.1 4.1 0 0 1 5.8 0") +
			"<circle class=\"" + (level >= 1 ? "gn-on" : "gn-off") + " gn-dot\" cx=\"12\" cy=\"19.2\" r=\"1.4\"/>" +
			cross + "</svg>";
	},

	renderIcon () {
		if (!this.button) return;
		const s = this.netStatus;
		let label = "Network status unknown";
		if (s) {
			const link = s.kind === "ethernet" ? "Wired" : s.kind === "wifi" ? "Wi-Fi" + (s.signal !== null ? " " + s.signal + "%" : "") : "No network";
			label = link + (s.online ? "" : ", no internet") + ". Tap for the guest Wi-Fi code.";
		}
		this.button.setAttribute("aria-label", label);
		this.button.title = label;
		this.button.innerHTML = this.iconSvg();
	},

	openPopup () {
		this.closePopup();
		this.sendSocketNotification("GN_GUEST_REQUEST");
		const backdrop = document.createElement("div");
		backdrop.className = "gn-backdrop";
		backdrop.addEventListener("click", (ev) => {
			if (ev.target === backdrop) this.closePopup();
		});
		const card = document.createElement("div");
		card.className = "gn-card";
		backdrop.appendChild(card);
		document.body.appendChild(backdrop);
		this.popup = { backdrop, card };
		this.renderPopup();
		this.closeTimer = setTimeout(() => this.closePopup(), this.config.closeAfterMs);
	},

	closePopup () {
		clearTimeout(this.closeTimer);
		if (this.popup) this.popup.backdrop.remove();
		this.popup = null;
	},

	renderPopup () {
		if (!this.popup) return;
		const card = this.popup.card;
		card.replaceChildren();
		const g = this.guest;

		const heading = document.createElement("div");
		heading.className = "gn-heading";
		heading.textContent = g && g.ssid ? "Scan the QR code to join “" + g.ssid + "”" : this.config.title;
		card.appendChild(heading);

		if (!g) {
			const wait = document.createElement("div");
			wait.className = "gn-note";
			wait.textContent = "Loading…";
			card.appendChild(wait);
		} else if (g.error) {
			const err = document.createElement("div");
			err.className = "gn-note";
			err.textContent = g.error;
			card.appendChild(err);
		} else {
			const qr = document.createElement("div");
			qr.className = "gn-qr";
			qr.innerHTML = g.svg; // SVG generated by our own node_helper (qrcode package)
			card.appendChild(qr);
			const hint = document.createElement("div");
			hint.className = "gn-note";
			hint.textContent = "Point your phone camera at the code.";
			card.appendChild(hint);
			if (this.config.showPassword && g.password) {
				const pw = document.createElement("div");
				pw.className = "gn-password";
				const label = document.createElement("span");
				label.textContent = "Password";
				const value = document.createElement("strong");
				value.textContent = g.password;
				pw.append(label, value);
				card.appendChild(pw);
			}
		}

		const close = document.createElement("button");
		close.type = "button";
		close.className = "gn-close";
		close.textContent = "Done";
		close.addEventListener("click", () => this.closePopup());
		card.appendChild(close);
	},

	socketNotificationReceived (notification, payload) {
		if (notification === "GN_STATUS") {
			this.netStatus = payload;
			this.renderIcon();
		} else if (notification === "GN_GUEST") {
			this.guest = payload;
			this.renderPopup();
		}
	}
});
